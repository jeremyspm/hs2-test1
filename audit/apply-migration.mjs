/* ── 9b. authored stems — the recontextualisation layer ──────────────────────
   Canvas kept a question's context OUTSIDE the question: a quiz title above it, a
   group preamble, an underline, a hyperlink. The harvest took the question and left
   the context, so 28 of the lecturer's cards arrive unintelligible on their own —
   "Complete the passage. (MODULE 1.1)" is a title, not a question, and it is the stem
   on eight separate cards covering eight unrelated topics.

   ONLY `q` IS TOUCHED. The answer, options, passage, blanks and marking points are
   untouched and still diff against the capture, so the card's authority is unchanged;
   what changes is that you can now tell what it is asking. The original is kept on the
   card as `qOrig` and the engine shows it, so her wording is never lost — this is a
   layer over her question, not a replacement for it.

   Keyed on the full ckey computed from the card AS HARVESTED. This runs before
   anything rewrites `q`, and apply-migration rebuilds from source every run, so the
   key is always computed against the original — the same reason selfmark-answers.json
   can key on `q` while writing `a`. See stems.json for the rest.

   NOTE THE ORDERING CONSTRAINT: this MUST run after applyExplanations and
   applySelfMarkAnswers, both of which look their targets up by the original question.
   Restem first and 28 cards silently lose their explanations. */
const STEMS = JSON.parse(fs.readFileSync(path.join(HERE, 'stems.json'), 'utf8')).stems ?? [];

function applyStems(list) {
  const byKey = new Map();
  for (const c of list) {
    const k = ckey(c);
    if (!byKey.has(k)) byKey.set(k, []);
    byKey.get(k).push(c);
  }
  const problems = [];
  const seen = new Set();
  let applied = 0, fixed = 0;

  for (const e of STEMS) {
    if (seen.has(e.k)) { problems.push(`${e.k}: listed twice`); continue; }
    seen.add(e.k);
    if (e.q && e.sub) { problems.push(`${e.k}: needs at most one of \`q\` or \`sub\``); continue; }
    if (!e.q && !e.sub && !e.fix) { problems.push(`${e.k}: needs one of \`q\`, \`sub\` or \`fix\``); continue; }

    const hits = byKey.get(e.k);
    if (!hits) { problems.push(`${e.k}: matches no card — the question it was written for has changed. Anchor: "${String(e.was).slice(0, 70)}…"`); continue; }
    if (hits.length > 1) { problems.push(`${e.k}: matches ${hits.length} cards — the key is not unique`); continue; }
    const c = hits[0];

    /* The anchor is the second guard and the only one a human can read. Eight cards
       share the stem "Complete the passage. (MODULE 1)", so the key alone is doing all
       the work of telling them apart; if it ever drifted, this is what catches it. */
    if (strip(String(c.q)).replace(/\s+/g, ' ').trim() !== String(e.was).replace(/\s+/g, ' ').trim()) {
      problems.push(`${e.k}: anchor does not match the card's question.\n        want: ${String(e.was).slice(0, 90)}\n        got : ${strip(String(c.q)).slice(0, 90)}`);
      continue;
    }
    if (c.qOrig) { problems.push(`${e.k}: card already carries a qOrig — refusing to restem twice`); continue; }

    /* ── `fix`: the same surgical substitution, applied to the card's BODY ────────────
       Six reader flags in the first round-trip were typos inside her own passages and
       dropdown options — "tunica medi", "internal elastic lanmina", "Acetyl choline",
       "Juxta glomerular". Every one of them was verified present in the raw capture
       first, so these are hers and not the parser's; and a verbatim card is provenance,
       not scripture — the original is kept and shown, exactly as `qOrig` already works
       for stems.

       WHAT MAY BE TOUCHED, AND THE KEY CONSEQUENCE OF EACH. `csig` folds in `text` and
       `pairs` but NOT `blanks`, so a `text` or `pairs` fix changes the card's ckey and a
       `blanks` fix does not. That is the same deliberate reset restemming already
       accepts: a reader's progress on a passage that has been corrected does not carry
       over, and a stale explanation cannot silently reattach. It is safe HERE and only
       here because explanations.json is applied earlier in this file, against the
       pre-edit card — the ordering that the flags.mjs fixture bug already taught us to
       hold on to.

       Same exactly-once rule as `sub`, for the same reason: a substitution that matches
       twice edits somewhere nobody looked, and one that matches zero times is a fix that
       has silently rotted. */
    if (e.fix) {
      const before = JSON.stringify([c.text ?? null, c.pairs ?? null, c.blanks ?? null]);
      let bad = false;
      const subOne = (s, pairs, label) => {
        let out = String(s);
        for (const [from, to] of pairs) {
          const n = out.split(from).length - 1;
          if (n > 1) { problems.push(`${e.k}: ${label} substitution "${from.slice(0, 40)}" matched ${n} times, needs at most 1`); bad = true; return out; }
          if (n === 1) { out = out.split(from).join(to); hitCount[label] = (hitCount[label] ?? 0) + 1; }
        }
        return out;
      };
      var hitCount = {};
      if (e.fix.text) {
        if (!c.text) { problems.push(`${e.k}: fix.text on a card with no passage`); continue; }
        c.textOrig = c.text; c.text = subOne(c.text, e.fix.text, 'text');
      }
      if (e.fix.pairs) {
        if (!c.pairs) { problems.push(`${e.k}: fix.pairs on a card with no pairs`); continue; }
        c.pairsOrig = JSON.parse(JSON.stringify(c.pairs));
        c.pairs = c.pairs.map(p => p.map(v => subOne(v, e.fix.pairs, 'pairs')));
      }
      if (e.fix.blanks) {
        if (!c.blanks) { problems.push(`${e.k}: fix.blanks on a card with no blanks`); continue; }
        c.blanksOrig = JSON.parse(JSON.stringify(c.blanks));
        c.blanks = c.blanks.map(b => Object.assign({}, b, { options: b.options.map(o => subOne(o, e.fix.blanks, 'blanks')) }));
      }
      /* `order` — presentation only, and the one fix that is not a substitution. Her
         answer key for a find-the-error question listed the numbered parts 1,4,3,2,5,
         so the card asked the reader to check five numbered claims in a scrambled
         order. Nothing about the content changes; the pairs are the same pairs. Asserted
         as a permutation so a typo in the list cannot drop or duplicate a pair. */
      if (e.fix.order) {
        if (!c.pairs) { problems.push(`${e.k}: fix.order on a card with no pairs`); continue; }
        const o = e.fix.order;
        const ok = o.length === c.pairs.length &&
          new Set(o).size === o.length && o.every(i => Number.isInteger(i) && i >= 0 && i < c.pairs.length);
        if (!ok) { problems.push(`${e.k}: fix.order is not a permutation of ${c.pairs.length} pairs`); continue; }
        if (o.every((v, i) => v === i)) { problems.push(`${e.k}: fix.order is the order it already has`); continue; }
        if (!c.pairsOrig) c.pairsOrig = JSON.parse(JSON.stringify(c.pairs));
        c.pairs = o.map(i => c.pairs[i]);
      }
      /* Every declared substitution must land somewhere on this card, or the entry is
         describing text that is no longer there. */
      for (const f of ['text', 'pairs', 'blanks']) {
        if (e.fix[f] && (hitCount[f] ?? 0) !== e.fix[f].length) {
          problems.push(`${e.k}: fix.${f} declared ${e.fix[f].length} substitution(s), ${hitCount[f] ?? 0} matched`); bad = true;
        }
      }
      if (bad) continue;
      if (JSON.stringify([c.text ?? null, c.pairs ?? null, c.blanks ?? null]) === before) {
        problems.push(`${e.k}: fix changed nothing`); continue;
      }
      fixed++;
      if (!e.q && !e.sub) { applied++; continue; }   // fix-only entry: no stem to rewrite
    }

    let next = String(c.q);
    if (e.sub) {
      for (const [from, to] of e.sub) {
        const n = next.split(from).length - 1;
        /* Exactly once. A substitution that matched twice would edit a second place
           nobody looked at; one that matched zero times is a rule written against text
           that has since changed, and silently doing nothing is how a fix rots. */
        if (n !== 1) { problems.push(`${e.k}: substitution "${from.slice(0, 45)}…" matched ${n} times, needs exactly 1`); next = null; break; }
        next = next.split(from).join(to);
      }
      if (next === null) continue;
    } else {
      next = e.q;
    }
    if (strip(next).trim() === strip(String(c.q)).trim()) { problems.push(`${e.k}: the new stem is identical to the old one`); continue; }

    c.qOrig = c.q;
    c.q = next;
    applied++;
  }

  if (problems.length) {
    console.error(`✗ ${problems.length} problem(s) in stems.json:\n   ` + problems.join('\n   '));
    process.exit(1);
  }
  return { applied, fixed };
}

/* ── 9c. cards that are broken in the COURSE, not in the import ──────────────
   Every so often the capture is faithful and the question is still unanswerable,
   because what Canvas published was already broken. Those cards cannot be edited —
   that is the whole promise of the verbatim tier — and must not be dealt as
   questions, because marking a reader wrong on a string that does not parse teaches
   nothing and makes them doubt themselves. `damaged` carries the reason; the engine
   keeps the card readable everywhere and deals it nowhere.

   VERIFY AGAINST THE CAPTURE BEFORE ADDING ONE. The default assumption for a
   mangled card is that the harvest mangled it, and that is a bug to fix in the
   parser, not a label to stick on the card. Each entry below was checked against the
   raw questions.json first and the damage is present there. */
const DAMAGED = [
  {
    k: 'koworns',
    was: 'Do the matching exercise to show your understanding of the terms chronotropic and inotropic.',
    why: "The marking key published for this question is inconsistent: “Decreases both chronotropic output” is used as the answer to one prompt and as a prompt in its own right, and a seventh prompt reads “A tion of norepine on myocardial cellshrine”. Both are exactly as Canvas served them.",
  },
];

function applyDamaged(list) {
  const byKey = new Map(list.map((c) => [ckey(c), c]));
  const problems = [];
  let n = 0;
  for (const d of DAMAGED) {
    const c = byKey.get(d.k);
    if (!c) { problems.push(`${d.k}: matches no card. Anchor: "${d.was.slice(0, 70)}"`); continue; }
    if (strip(String(c.q)).replace(/\s+/g, ' ').trim() !== d.was.replace(/\s+/g, ' ').trim()) {
      problems.push(`${d.k}: anchor does not match — got "${strip(String(c.q)).slice(0, 70)}"`); continue;
    }
    c.damaged = d.why;
    n++;
  }
  if (problems.length) { console.error(`✗ ${problems.length} problem(s) in the DAMAGED list:\n   ` + problems.join('\n   ')); process.exit(1); }
  return n;
}

/* ── 10. the cull — manufactured cards are DROPPED, not demoted ──────────────
   Was: `bg:true` demoted these out of the default queue but kept them in the pack
   behind a one-tap switch. That was the right call while the question was "how many
   cards is too many". It is the wrong call now, because the question turned out to be
   a different one.

   Measured across the pack, the `textbook` tier reads HARDER than the lecturer's own
   material — median Flesch 39 against her 53, roughly grade 12 against grade 9.5.
   Cards written to fill a floor were the least readable thing in the tool, and they
   were sitting on ground her own questions already hold. A switch that hides them is
   not the fix; not shipping them is.

   THE RULE IS UNCHANGED AND STILL DELIBERATELY CONSERVATIVE. A card goes only if
   EVERY focus point it touches — `crit` and every `alsoCrit` — already has a sourced
   card. One unsourced focus point anywhere on the card and it stays. That is what
   keeps 17 load-bearing textbook cards in the pack: the ones holding up cvs-1,
   resp-9, resp-15 and resp-16, the four focus points with no sourced card anywhere.

   NOTHING IS LOST. The dropped cards are still in pack.source.js / coverage-fill.js
   and their authored explanations are still in explanations.json, so flipping KEEP_BG
   restores them exactly. This is a shipping decision, not a deletion.

   RUNS LAST, AFTER the overlays and the dedupe. applyExplanations fails the build on
   any entry that matches no card, and ~120 of those entries are written for cards this
   drops — cull first and the build dies on its own bookkeeping. */
const KEEP_BG = process.argv.includes('--keep-background');
const sourcedCrits = new Set();
for (const c of [...cards, ...harvested, ...caseCards, ...COVERAGE_FILL]) {
  if (c.tier === 'textbook') continue;
  for (const id of [c.crit, ...(c.alsoCrit ?? [])].filter(Boolean)) sourcedCrits.add(id);
}
const critsOf = (c) => [c.crit, ...(c.alsoCrit ?? [])].filter(Boolean);
/* A CARD BUILT ON A FIGURE IS NEVER MANUFACTURED PADDING, whatever its prose tier says.
   The first run of this cull dropped all 15 — every diagram-reading card in the pack —
   and the build caught it only because it also counts wired figures. They are tiered
   `textbook` because their PROSE is standard physiology, but the thing being studied is
   the diagram, and those diagrams are ported byte-for-byte from hs2-module1, which cites
   its slides. So the figure is sourced even where the sentence around it is not.

   They are also the shape this whole rebuild is trying to get more of: "Read the trace.
   Match each deflection to what it represents." is nine words and a picture, not the
   paragraph the cull exists to remove. Tier is the wrong test for them. */
const isManufactured = (c) => {
  const ids = critsOf(c);
  if (c.fig) return false;
  return c.tier === 'textbook' && ids.length > 0 && ids.every((id) => sourcedCrits.has(id));
};
function cullBackground(list) {
  const dropped = list.filter(isManufactured);
  const kept = KEEP_BG ? list : list.filter((c) => !isManufactured(c));

  /* The gate that still means something: a focus point with NOTHING under it is a
     hole the reader meets as an empty topic. Zero is a build failure; thin is not —
     see `thin` below. */
  const per = {};
  for (const c of kept) for (const id of critsOf(c)) per[id] = (per[id] ?? 0) + 1;
  const empty = (criteria ?? []).filter((cr) => !per[cr.id]);
  if (empty.length) {
    console.error(`✗ the cull empties ${empty.length} focus point(s): ${empty.map((c) => c.id).join(', ')}`);
    process.exit(1);
  }

  /* THIN IS A FACT ABOUT HER COVERAGE, NOT A BUILD FAILURE — the meaning of the
     floor changes with this commit. It used to say "author until you reach 6", and 12
     focus points were reaching it on manufactured cards alone. Under the new rule the
     only way to clear it is to mine more of her material, and if there is no more to
     mine then the honest number is the low one. So the floor stops blocking the build
     and starts DECLARING: the count ships in the pack, the tool says it to the reader,
     and this list is the work list for the next mining pass.
     ([[self-explaining-ui-policy]] — warn, do not fake confidence.) */
  const { min: MIN = 0, blindMin: BLIND_MIN = 0 } = pack.coverage ?? {};
  const thin = (criteria ?? [])
    .map((cr) => ({ id: cr.id, n: per[cr.id] ?? 0, floor: cr.blind ? Math.max(MIN, BLIND_MIN) : MIN }))
    .filter((x) => x.n < x.floor);

  return { kept, dropped, thin, min: Math.min(...(criteria ?? []).map((cr) => per[cr.id] ?? 0)) };
}

