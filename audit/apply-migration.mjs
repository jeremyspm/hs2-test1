/* ── 7. cull the duplicate cards, keeping BOTH sources ───────────────────────
   Five harvested questions appear twice — same question, same answer, same focus
   point — captured from two different Canvas quizzes. That is not a double import:
   it is the same five questions genuinely set on two lab quizzes. The engine keys a
   card on type + question + a signature of its own content, so it already treats
   these as one card and deals only the first; the second was dead weight.

   Culling them by deleting one would throw away the more interesting half of the
   fact. So one card survives and carries BOTH evidence records — the reader loses a
   question they were never shown twice anyway, and gains "this exact question has
   been set twice", which is the strongest signal in the pack. `provDetailHTML` has
   always rendered `ev` as an array. */
/* strip/hash/csig/ckey moved to ./ckey.mjs 11 Aug 2026 — build.mjs's spine gate needs the
   same hash, and a third copy of it is how the two that already exist start to drift. */

function dedupe(list) {
  const first = new Map(), out = [], merged = [];
  for (const c of list) {
    const k = ckey(c), keep = first.get(k);
    if (!keep) { first.set(k, c); out.push(c); continue; }
    const evs = [].concat(keep.ev ?? []), seen = new Set(evs.map(e => JSON.stringify(e)));
    for (const e of [].concat(c.ev ?? [])) if (!seen.has(JSON.stringify(e))) { evs.push(e); seen.add(JSON.stringify(e)); }
    if (evs.length) keep.ev = evs.length === 1 ? evs[0] : evs;
    merged.push({ q: strip(c.q).slice(0, 58), quiz: ([].concat(c.ev ?? [])[0] ?? {}).quiz ?? '?' });
  }
  return { cards: out, merged };
}

/* ── 8. authored explanations ────────────────────────────────────────────────
   `why` is the line a reader gets after answering a drill card wrong, and `model` is
   the extra credit note under a written answer's marking points. Neither can live in
   the harvested cards: those are the lecturer's own questions, reproduced unedited and
   proven so by a diff against the capture, and `pack.source.js` is the pre-migration
   source and holds none of them. So they sit in their own file, keyed by the SAME
   ckey the dedupe uses — a hash of the card's type, question and content.

   That key choice is the point. Edit a question and its key changes, so a stale
   explanation cannot silently reattach itself to a card it was not written for; it
   fails the build instead. The `q` anchor is a second guard and a way to read the
   file: three `match` cards share the question "Match each statement to the correct
   term from Hannetjie's wordlist", and only their contents tell them apart.

   Refusing to overwrite an existing value is deliberate. The last pass lost ~97
   authored explanations to a generator that wrote `why` without looking, and the
   whole fix was to notice. This one looks. */
const EXPL = JSON.parse(fs.readFileSync(path.join(HERE, 'explanations.json'), 'utf8'));
const DRILL_TYPES = ['mcq', 'match', 'cloze', 'tfset', 'order'];
const stemOf = (c) => strip([c.q, c.text, (c.options ?? []).join(' '), (c.pairs ?? []).map(p => p[0]).join(' '),
  (c.statements ?? []).map(s => s.s).join(' '), (c.steps ?? []).join(' ')].filter(Boolean).join(' '));
const normA = (s) => String(s).replace(/\s+/g, ' ').trim().toLowerCase();

function applyExplanations(list) {
  const byKey = new Map();
  for (const c of list) {
    const k = ckey(c);
    if (!byKey.has(k)) byKey.set(k, []);
    byKey.get(k).push(c);
  }
  const problems = [];
  const applied = { why: 0, model: 0 };
  for (const [field, entries] of [['why', EXPL.why ?? []], ['model', EXPL.model ?? []]]) {
    const seen = new Set();
    for (const e of entries) {
      if (seen.has(e.k)) { problems.push(`${field} ${e.k}: listed twice`); continue; }
      seen.add(e.k);
      const hits = byKey.get(e.k);
      if (!hits) { problems.push(`${field} ${e.k}: matches no card — the question it was written for has changed. Anchor: "${e.q}"`); continue; }
      for (const c of hits) {
        if (!normA(stemOf(c)).includes(normA(e.q))) { problems.push(`${field} ${e.k}: anchor "${e.q}" appears nowhere on the card it keys to`); continue; }
        if (field === 'why' && !DRILL_TYPES.includes(c.type)) { problems.push(`${field} ${e.k}: card is a ${c.type} — \`why\` is for machine-marked cards`); continue; }
        if (field === 'model' && c.type !== 'saq') { problems.push(`${field} ${e.k}: card is a ${c.type}, not a written answer`); continue; }
        if (c[field] && String(c[field]).trim()) { problems.push(`${field} ${e.k}: the card already carries a ${field} — refusing to overwrite authored content`); continue; }
        c[field] = e.t;
        applied[field]++;
      }
    }
  }
  if (problems.length) {
    console.error(`✗ ${problems.length} problem(s) in explanations.json:\n   ` + problems.join('\n   '));
    process.exit(1);
  }

  /* `--emit-missing` writes out the ckey of every machine-marked card still lacking a
     `why`, AFTER the overlay above has been applied, so the list is what is genuinely
     unauthored rather than what merely starts empty.

     It exists so explanations get written against real keys. The alternative is a helper
     script carrying its own copy of ckey()/strip()/csig(), which is a second
     implementation of a hash whose entire job is to be identical — and when it drifts,
     every key it emits resolves to no card and the whole batch is rejected at the gate
     with nothing to show which half was wrong. Emitting from inside the module that owns
     the hash makes that class of mistake impossible. Read-only: writes one file and
     changes nothing about the migration. */
  if (process.argv.includes('--emit-missing')) {
    const rows = [];
    for (const [k, cs] of byKey) for (const c of cs) {
      if (!DRILL_TYPES.includes(c.type) || String(c.why ?? '').trim()) continue;
      rows.push({
        k, type: c.type, crit: c.crit ?? null,
        q: strip(c.q).slice(0, 260),
        options: c.options, correct: c.options ? c.options[c.correct] : undefined,
        pairs: c.pairs, statements: c.statements, answers: c.answers, blanks: c.blanks,
        quiz: ([].concat(c.ev ?? [])[0] ?? {}).quiz ?? null,
      });
    }
    fs.writeFileSync(path.join(HERE, 'missing-explanations.json'), JSON.stringify(rows, null, 1));
    console.log(`  --emit-missing: ${rows.length} card(s) still need a \`why\` → audit/missing-explanations.json`);
  }
  return applied;
}

/* ── 8b. authored answers for the self-marked cards ──────────────────────────
   Same overlay shape as the explanations above and for the same reason: these are
   Hannetjie's questions, reproduced unedited, so the answer cannot live on the card.

   The KEY IS DIFFERENT, and deliberately. `explanations.json` keys on the full ckey —
   type, question and a signature of the card's content — which is exactly right for a
   `why`, because `why` is not part of the signature. It would be self-defeating here:
   `csig` folds in `a`, so the moment this file wrote an answer the key it was found
   under would change, and the next run would fail to find it. So these key on the
   QUESTION alone. All 38 are unique under it and the gate below proves it every run,
   rather than trusting that they stay unique.

   Applied AFTER voicePass, because voicePass can rewrite `q` (one exact rule does) and
   the keys were computed against the finished pack. */
const SELFMARK = JSON.parse(fs.readFileSync(path.join(HERE, 'selfmark-answers.json'), 'utf8'));
const SELFMARK_FOOTER = `<div class="srcline"><b>Self-marked question.</b> Canvas published no marking schedule for this one, so the answer above is written for this pack from the Module 1 lecture material — it is not ${LS} own model answer. Check it against the slides if anything looks off.</div>`;
const qkey = (c) => hash('flash|' + strip(c.q));

function applySelfMarkAnswers(list) {
  const targets = list.filter((c) => c.selfMark);
  const byKey = new Map();
  for (const c of targets) {
    const k = qkey(c);
    if (!byKey.has(k)) byKey.set(k, []);
    byKey.get(k).push(c);
  }
  const problems = [];
  /* A key MAY address more than one card, and five of them do: those are the harvested
     questions captured from two different quizzes, which §7 below merges into one card.
     Same question, same answer, so applying to both is correct and the survivor keeps
     it. What must never happen is two DIFFERENT questions landing on one key — a hash
     collision — because then one card silently gets an answer written for the other.
     So the check is on the questions, not on the count. */
  for (const [k, cs] of byKey) {
    const qs = new Set(cs.map((c) => normA(strip(c.q))));
    if (qs.size > 1) problems.push(`${k}: HASH COLLISION — ${qs.size} different questions share this key: ${[...qs].map((q) => `"${q.slice(0, 50)}…"`).join(' vs ')}`);
  }
  const seen = new Set();
  let applied = 0;
  for (const e of SELFMARK.answers ?? []) {
    if (seen.has(e.k)) { problems.push(`${e.k}: listed twice`); continue; }
    seen.add(e.k);
    const hits = byKey.get(e.k);
    if (!hits) { problems.push(`${e.k}: matches no self-marked card — the question it was written for has changed. Anchor: "${e.q}"`); continue; }
    for (const c of hits) {
      if (!normA(strip(c.q)).includes(normA(e.q))) { problems.push(`${e.k}: anchor "${e.q}" appears nowhere in the question it keys to`); continue; }
      if (String(c.a ?? '').trim()) { problems.push(`${e.k}: the card already carries an answer — refusing to overwrite authored content`); continue; }
      c.a = e.t + SELFMARK_FOOTER;
      applied++;
    }
  }
  /* The floor. Everything above catches a BAD entry; this catches a MISSING one, which
     is the failure that shipped last time — a card with no answer reads as finished. */
  for (const c of targets) {
    if (!String(c.a ?? '').trim()) problems.push(`no answer authored for self-marked card (k=${qkey(c)}): "${strip(c.q).slice(0, 70)}…"`);
  }
  if (problems.length) {
    console.error(`✗ ${problems.length} problem(s) in selfmark-answers.json:\n   ` + problems.join('\n   '));
    process.exit(1);
  }
  return { applied, targets: targets.length };
}

