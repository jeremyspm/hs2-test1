/* ── 4. declared quantity corrections ────────────────────────────────────────
   Explicit and reviewable rather than a regex sweep. Each one replaces a value the
   declared table rejects with the value HER slide gives. These are our cards, not her
   words, so correcting them toward her figure is the whole point. */
const TEXT_FIXES = [
  [/(?<![\w.])159 mmHg/g, '159.6 mmHg', 'atmospheric PO₂ — her RESP2 slide 4 gives 159.6'],
  [/(?<![\w.])159\b(?! ?\.6)(?=[^\d]*mmHg)/g, '159.6', 'atmospheric PO₂ written without its unit'],
  [/PCO₂ ≈ 0\.3 mmHg/g, 'PCO₂ ≈ 0.2 mmHg', 'atmospheric PCO₂ — her slide gives 0.2, not the 0.3 of another textbook'],
  [/(?<![\w.])0\.3 mmHg/g, '0.2 mmHg', 'atmospheric PCO₂ — her slide gives 0.2'],
  /* One card writes the value as the start of a range, "(0.3 → ~40 mmHg)", so the unit
     does not follow the number and a "0.3 mmHg" pattern misses it entirely. */
  [/\(0\.3 (?=→|->)/g, '(0.2 ', 'atmospheric PCO₂ written as the start of a range'],
];
const fixCounts = new Map(TEXT_FIXES.map(f => [f[2], 0]));
const applyFixes = (v) => {
  if (typeof v === 'string') {
    let s = v;
    for (const [re, to, why] of TEXT_FIXES) {
      const before = s;
      s = s.replace(re, to);
      if (s !== before) fixCounts.set(why, fixCounts.get(why) + 1);
    }
    return s;
  }
  if (Array.isArray(v)) return v.map(applyFixes);
  if (v && typeof v === 'object') {
    return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, k === 'ev' || k === 'pointEv' ? x : applyFixes(x)]));
  }
  return v;
};

