/* ── 6. voice pass ───────────────────────────────────────────────────────────
   The pack was written in the voice of the two people who built it, talking about a
   third: 204 references to the lecturer as "her" or "she". A student opening this
   cold does not know who "she" is, so every one of those is a word spent decoding
   rather than learning. Named, they read warmer AND clearer.

   This is a list of exact rules, not a regex sweep, for two reasons that a sweep
   would have got wrong:

   1. NOT EVERY "her" IS THE LECTURER. Ten of them are patients in clinical
      scenarios — Kalama choking on bread, La'akea's punctured pleura, Oliana after
      exercise, Jill in hypovolaemic shock. Those pronouns are correct clinical
      prose about the person in the case and must not be touched. So the pass runs
      over a WHITELIST of fields that describe the lecturer, and the scenario fields
      (`text`, `points`, `options`, `statements`, `steps`, `pairs`, `blanks`) are
      never in it.
   2. 39 of the matches live inside `fig`, next to megabytes of base64 image data.
      They turned out to be a real alt attribute — but a blind pass over the file
      would have been one lucky escape away from corrupting the images.

   Every rule is asserted to fire, and the whole pack is re-scanned afterwards, so a
   rule that silently stops matching fails the build instead of leaking a "she". */
const VOICE_FIELDS = ['a', 'model', 'srcNote', 'why'];
const VOICE_RULES = [
  // ---- machine-generated sourcing notes (migrate.mjs writes these) ----
  [/^her QUESTION is at /, 'The QUESTION is at '],
  [/\bin her model answers\b/g, `in ${LS} model answers`],
  [/\bthe number is not hers\b/g, `the number is not ${LS}`],
  [/^Her slide /, `${LS} slide `],
  [/^Her deck /, `${LS} deck `],
  [/\bher slides label the DRG\b/, `${LS} slides label the DRG`],
  [/\bHer clearest statement is slide 9\b/, `${LS} clearest statement is slide 9`],
  // ---- hand-authored answers ----
  [/\bher slide does not mention either\b/, `${LS} slides do not mention either`],
  [/\bwhich she notes is\b/, `which ${L} notes is`],
  [/\(Her slide 6 writes/, `(${LS} slide 6 writes`],
  [/use her 70 if she asks for a figure/, `use the lecture's 70 if a figure is asked for`],
  [/\bshe does not use those terms\b/, `${L} does not use those terms`],
  // ---- hand-authored marking notes ----
  [/\bHer note:/, `${LS} note:`],
  [/\bHer follow-up question:/, `${LS} follow-up question:`],
  [/Note she scored that question at only/, 'Note that question scored only'],
  [/not her mark allocation/, `not ${LS} mark allocation`],
  [/^Her own model answer for this question/, `${LS} own model answer for this question`],
  /* Naming beats a pronoun, but only up to a point. Substituting the name at every
     pronoun turned one model answer into "Reproduced from Hannetjie's own model
     answer, including the direct/indirect split Hannetjie uses. Hannetjie's RAAS
     summary table…" — three times in two sentences. Where the possessor is already
     established by the sentence before, the second reference drops it entirely
     rather than repeating the name. */
  [/the marking schedule she published/, 'the marking schedule published'],
  [/Reproduced from her own model answer/, `Reproduced from ${LS} own model answer`],
  [/the direct\/indirect split she uses\. Her RAAS summary table/, 'the direct/indirect split it makes. The RAAS summary table in that deck'],
  // ---- point-level evidence notes (pointEv[].why) ----
  [/^Her material names where each cell MATURES/, `${LS} material names where each cell MATURES`],
  [/^She asks how the COVID-19 vaccine works/, `${L} asks how the COVID-19 vaccine works`],
  /* ---- jargon that leaked out of the audit vocabulary into student-facing prose ----
     `textbook-tier` → `background reading` was here and is RETIRED. Its last target was
     the resp-9 acknowledged-gap note, and when the three Module 1.2 quizzes gave resp-9
     three of Hannetjie's own questions that note went with them — so the rule matched
     nothing, and the dead-rule gate below failed the build rather than letting it sit
     there looking useful. That is the gate doing its job; the answer to it is to delete
     the rule, not to keep a string alive for it to find.

     Put it back the moment `textbook-tier` appears in `a`, `model`, `srcNote` or `why`
     again — the audit vocabulary must not reach the reader. */
];
// exact single strings, applied only to the one field each belongs to
const VOICE_EXACT = {
  q:   [['from her wordlist.', `from ${LS} wordlist.`]],
  fig: [['alt="Figure from her quiz question"', `alt="Figure from ${LS} quiz question"`]],
};
const voiceHits = new Map(VOICE_RULES.map(r => [String(r[0]), 0]));
const exactHits = new Map(Object.values(VOICE_EXACT).flat().map(r => [r[0], 0]));
const voice = (s) => {
  if (typeof s !== 'string') return s;
  for (const [re, to] of VOICE_RULES) {
    const before = s;
    s = s.replace(re, to);
    if (s !== before) voiceHits.set(String(re), voiceHits.get(String(re)) + 1);
  }
  return s;
};
function voicePass(card) {
  for (const f of VOICE_FIELDS) if (typeof card[f] === 'string') card[f] = voice(card[f]);
  for (const [f, rules] of Object.entries(VOICE_EXACT)) {
    if (typeof card[f] !== 'string') continue;
    for (const [from, to] of rules) {
      if (!card[f].includes(from)) continue;
      exactHits.set(from, exactHits.get(from) + card[f].split(from).length - 1);
      card[f] = card[f].split(from).join(to);
    }
  }
  // pointEv sits outside applyFixes on purpose (it is evidence), but its `why` is prose
  if (Array.isArray(card.pointEv)) card.pointEv = card.pointEv.map(pe => pe && typeof pe.why === 'string' ? { ...pe, why: voice(pe.why) } : pe);
  return card;
}

