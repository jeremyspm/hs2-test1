/* Re-scan the whitelisted fields. A leftover here means a rule stopped matching, or
   new prose has arrived that talks about the lecturer in the third person.

   `q` is deliberately NOT scanned. It is the one field that holds both kinds of
   sentence — one card says "from her wordlist" (the lecturer, rewritten above by an
   exact rule) and three describe patients: "a woman develops persistent swelling of
   her right arm", "explain what her body is doing". Those pronouns are correct
   clinical prose about the person in the case and must survive every pass. Scanning
   `q` for pronouns would fail the build on them forever. */
const LEFT = /\b(her|hers|she|She|Her|Hers)\b/;
const leaks = [];
for (const c of next.cards) {
  for (const f of VOICE_FIELDS) if (typeof c[f] === 'string' && LEFT.test(c[f]))
    leaks.push(`${f}: ${strip(c[f]).slice(0, 90)}`);
  if (typeof c.fig === 'string' && /alt="[^"]*\b(her|she)\b/i.test(c.fig)) leaks.push('fig alt text');
  for (const pe of c.pointEv ?? []) if (pe && LEFT.test(pe.why ?? '')) leaks.push(`pointEv.why: ${String(pe.why).slice(0, 90)}`);
}
for (const [k, v] of [['sources', next.sources], ['doorNote', next.doorNote]]) if (LEFT.test(v)) leaks.push(`${k}: leftover pronoun`);
for (const cr of next.criteria) if (LEFT.test(cr.acknowledgedGap ?? '')) leaks.push(`acknowledgedGap ${cr.id}`);
if (leaks.length) { console.error(`✗ ${leaks.length} lecturer reference(s) still in the third person:\n   ` + leaks.slice(0, 12).join('\n   ')); process.exit(1); }

