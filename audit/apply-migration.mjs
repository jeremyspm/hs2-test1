/* KEYED BY ARRAY INDEX, AND THEREFORE VERIFIED BY LABEL.

   `migration.json` holds one proposal per item — its tier and its evidence — addressed
   by position in pack.source.js. That is fine until pack.source.js is edited: delete one
   card and every card after it silently inherits its NEIGHBOUR'S tier, evidence and
   quote. Removing a single duplicated SAQ on 11 Aug 2026 did exactly that, and the only
   symptom was eleven `taught` cards quietly swapping provenance — the count stayed
   plausible, every card still had a badge, and nothing failed.

   Every proposal already carries `label`, the first 78 characters of the item it was
   written for, so the alignment is checkable. It is checked here rather than trusted:
   an overlay addressed by position must prove the position still means what it meant.
   To add or remove a card in pack.source.js, re-run migrate.mjs so the proposals move
   with it — do not renumber by hand. */
const LBL = (o) => String(o?.q ?? o?.term ?? o?.name ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim().slice(0, 40);
const propOf = (kind, i, item) => {
  const p = migration.proposals.find(p => p.kind === kind && p.i === i);
  if (!p || item === undefined) return p;
  const want = LBL(item), got = LBL({ q: p.label });
  if (want && got && want !== got) {
    console.error(`✗ migration.json is out of step with ${kind === 'card' ? 'pack.source.js' : 'the glossary'} at index ${i}:`);
    console.error(`    the ${kind} here : ${want}`);
    console.error(`    the proposal for : ${got}`);
    console.error('\n  Proposals are addressed BY POSITION, so an inserted or deleted item shifts every');
    console.error('  one after it onto the wrong tier, evidence and quote. Re-run audit/migrate.mjs.');
    console.error('\n✗ NOT WRITING.');
    process.exit(1);
  }
  return p;
};
