/* ONE FIELD, ONE JOB.

   `why` is the EXPLANATION a reader gets when they answer a drill card wrong. It is
   not a filing cabinet for sourcing notes — but that is what it had become: 306 of
   the 359 textbook cards carried "no citation — standard textbook content written
   for the pack" in `why`, and the drill view rendered that string as the reason the
   answer was wrong. 123 of them are auto-marked cards a student actually meets. Get
   a question wrong, and the tool explained itself in authoring vocabulary instead of
   teaching you anything.

   Sourcing notes now live in `srcNote`, which the engine shows under the source badge
   where it belongs. The generic one is rewritten into plain English rather than
   dropped: the coverage gate wants every textbook card to say why it has no citation,
   and that is still true — it just no longer says it in our words. */
const GENERIC_NOTE = 'no citation — standard textbook content written for the pack';
const PLAIN_NOTE = 'Nothing in the captured course material was found stating this, so it is here as background rather than as something the course itself has said.';
const sourceNote = (s) => (!s || s === GENERIC_NOTE || s === 'no citation — standard textbook content written for this pack') ? PLAIN_NOTE : s;

const retier = (o, kind, i) => {
  const p = propOf(kind, i, o);
  let out = stripOldSrc(o);
  if (!p) return { ...out, tier: 'textbook', srcNote: 'No migration proposal was found for this item, so its sourcing is unknown.' };
  out.tier = p.tier;
  if (p.tier === 'taught' && p.ev) {
    const evs = (Array.isArray(p.ev) ? p.ev : [p.ev]).filter(Boolean);
    out.ev = evs.map(e => ({ src: e.src, loc: e.loc, quote: e.quote }));
  }
  else out.srcNote = sourceNote(p.why);
  if (p.candidateEv) out.candidateEv = p.candidateEv;   // kept for one-glance human review
  return applyFixes(out);
};

